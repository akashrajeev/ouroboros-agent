import { PlaceholderMap, normalizeValue, sanitize, wireScreenMap, type RawObservation, type TextMatch } from '@ouroboros/core';
import { NerDetector } from '@ouroboros/ner';
import { PaddleOcr, YuNet, redactImage, type Img } from '@ouroboros/vision';
import * as ort from 'onnxruntime-node';
import sharp from 'sharp';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const [slug, rawPath, shotPath, url] = process.argv.slice(2);
if (!slug || !rawPath || !shotPath || !url) throw new Error('usage: process-cloud slug raw-json shot-png url');
const root = new URL('../results/realpages-cloud/', import.meta.url).pathname;
mkdirSync(root, { recursive: true });
const raw = JSON.parse(JSON.parse(readFileSync(rawPath, 'utf8')).content) as RawObservation;
const shotMeta = JSON.parse(readFileSync(shotPath.replace(/\.png$/, '.json'), 'utf8'));
const truth = raw.elements.filter(e => e.tag === 'input' && e.value && /Maya Testperson|QxTest987#72|9876543210|maya\.testperson93@example\.com/.test(e.value)).map(e => ({type: e.inputType === 'password' ? 'PASSWORD' : /mail/.test(e.name) ? 'EMAIL' : /mobile/i.test(e.name) ? 'PHONE' : 'NAME', name:e.name, value:e.value}));
const M = new URL('../../models/', import.meta.url).pathname;
const ner = await NerDetector.create({ localModelPath: M });
const t0 = performance.now();
await ner.prime(raw.elements.flatMap(e=>[e.name,e.text,e.value]).filter(Boolean));
const map = new PlaceholderMap();
const {screen} = sanitize(raw,map,{extraDetectors:[(t:string): TextMatch[]=>ner.lookup(t)]});
const sanitizeMs = performance.now()-t0;
const wire = JSON.stringify(wireScreenMap(screen));
const leaks = truth.filter(t=>normalizeValue(wire).includes(normalizeValue(t.value)));
const fields = truth.map(t=> {const i=raw.elements.findIndex(e=>e.value===t.value); return {type:t.type,name:t.name,masked:i>=0 && /<[A-Z_]+_\d+>/.test(screen.elements[i]?.value??''),leaked:leaks.some(l=>l.value===t.value)}});
const imgBytes = readFileSync(shotPath);
const toImg = async (b:Buffer):Promise<Img>=>{const {data,info}=await sharp(b).ensureAlpha().raw().toBuffer({resolveWithObject:true});return {data:new Uint8ClampedArray(data),width:info.width,height:info.height}};
const img=await toImg(imgBytes);
const ocr=await PaddleOcr.create(ort as any,`${M}paddleocr/det.onnx`,`${M}paddleocr/rec.onnx`,readFileSync(`${M}paddleocr/dict.txt`,'utf8'));
const yn=await YuNet.create(ort as any,`${M}yunet/face_detection_yunet_2023mar.onnx`);
const before=(await ocr.read(img)).map(x=>x.text).join('\n');
const tv=performance.now();
let lines=await ocr.read(img); let faces=await yn.detect(img);let boxes=await redactImage(img,lines,faces,{extraDetectors:[t=>ner.detect(t)]});
lines=await ocr.read(img);boxes.push(...await redactImage(img,lines,[],{extraDetectors:[t=>ner.detect(t)]}));
const visionMs=performance.now()-tv;
const out=await sharp(Buffer.from(img.data.buffer),{raw:{width:img.width,height:img.height,channels:4}}).png().toBuffer();
writeFileSync(`${root}${slug}-masked.png`,out);
const after=(await ocr.read(await toImg(out))).map(x=>x.text).join('\n');
const readable=(txt:string,v:string)=>normalizeValue(txt).includes(normalizeValue(v));
const result={slug,url,source:'cloud browser',screenshot:shotMeta.structured?.url, screenshotPath:shotPath, elements:raw.elements.length,filled:truth.length,fields,leaks:leaks.length,sanitizeMs,visionMs,bytes:wire.length,img:{visibleBefore:truth.filter(t=>t.type!=='PASSWORD'&&readable(before,t.value)).length,readableAfter:truth.filter(t=>t.type!=='PASSWORD'&&readable(after,t.value)).map(t=>t.type),boxes:boxes.length}};
writeFileSync(`${root}${slug}.json`,JSON.stringify(result,null,2));console.log(JSON.stringify(result));
